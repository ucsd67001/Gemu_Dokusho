/* ============================================================
   場所の絵の上に置く、空のベンチと座っている人（場所のページ・場所の一覧の小さな絵・入口の看板・X に載る絵）
   ============================================================ */
import { 状態, 逃 } from "./共通.js";

/* 場所の絵と X に載る絵で同じにする決まり（2026-10-07 の2回目のリファクタリングで、2か所に書いていたものをここへ） */
// 座っている人を奥（y が小さい）から並べる。手前の人が上に重なるように
export const 奥から = (部屋, 席ら) => [...席ら].sort((a, b)=>(部屋.席[a.番]?.y || 0) - (部屋.席[b.番]?.y || 0));
/* 同じベンチに2人いるときは、2人目のユーザ名と書籍名を1段下げる
   （横に振り分けると、隣のブロックのユーザ名と書籍名とぶつかった） */
export const 下げるか = (席, 座られた番) => !!席.隣 && 座られた番.has(席.相方);

export const 置き = (席, 幅) => `left:${席.x}%;top:${席.y}%${幅 ? `;width:${席.幅}%` : ""}`;

/* 場所の絵の上に置く、空のベンチと座っている人（名札は無し）。
   場所の中の舞台と、一覧の小さな絵・入口の看板で同じものを使う（2026-09-29 配信者：サムネイルにもベンチを） */
export function 人とベンチ(部屋, 席ら){
  const 座られた = new Set(席ら.map(s=>s.番));
  // 誰も座っていない席には、空のベンチを置く（場所に 空き の絵があるときだけ）。絵の向きは 空きの向き
  const 空きら = 部屋.空き ? 部屋.席.flatMap((席, 番)=>座られた.has(番) ? [] : [{ y:席.y, 絵:`
    <div class="人 空き ${空きを反転するか(部屋, 席) ? "左向き" : ""}" style="${置き(席, true)}">
      <div class="姿"><img class="座る" src="${部屋.空き[席.姿] || 部屋.空き.顔}" alt=""></div>
    </div>` }]) : [];
  /* 奥（y が小さい）から描いて、手前のものが上に重なるようにする。
     ⚠️ 空のベンチも人も**まとめて**並べる（2026-10-04、芦ノ湖でベンチを前後2列にしたとき。
        前は空のベンチを先に全部描いていて、手前の空のベンチが、奥に座った人の下に隠れた） */
  const 人ら = 席ら.flatMap(s=>{
    const 席 = 部屋.席[s.番];
    if(!席) return [];
    const 人 = 状態.人々.get(s.uid), a = 人?.アバター || {};
    // 手前の席は背中を見せる。背中の絵がまだ無い人は、顔の絵のまま座る（めくる動きは背中では見えないので同じ絵）
    const 背中 = 席.姿 === "背中" && !!a.背中;
    return [{ y:席.y, 絵:`
    <div class="人 ${反転するか(人, 席, 背中) ? "左向き" : ""}" style="${置き(席, true)}">
      <div class="姿">
        <img class="座る" data-道="${逃(背中 ? a.背中 : a.座る)}" alt="">
        <img class="めくる" data-道="${逃(背中 ? a.背中 : a.めくる)}" alt="">
      </div>
    </div>` }];
  });
  return [...空きら, ...人ら].sort((a, b)=>a.y - b.y).map(x=>x.絵).join("");
}

/* 席の向き（テーブルの方）と、絵の向きが違えば左右を反転する。
   ⚠️ 絵は「右前を向く」と頼んでも左を向くことがあるので、描いたあとに見た向き（アバター.向き）を使う。
      本人が「向きを反対にする」を押していたら、さらに逆にする */
// 空のベンチの絵の向き（部屋.空きの向き。書いていなければ右）と、席の向きが違えば反転する
export function 空きを反転するか(部屋, 席){
  const 絵の向き = 部屋.空きの向き?.[席.姿] || "右";
  return 絵の向き !== 席.向き;
}

export function 反転するか(人, 席, 背中){
  const a = 人?.アバター || {};
  if(背中) return (a.背中の向き === "left" ? "左" : "右") !== 席.向き;
  let 絵の向き = a.向き === "left" ? "左" : "右";
  if(人?.反転) 絵の向き = 絵の向き === "左" ? "右" : "左";
  return 絵の向き !== 席.向き;
}
