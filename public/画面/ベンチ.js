/* ============================================================
   場所の絵の上に置く、空のベンチと座っている人（場所のページ・場所の一覧の小さな絵・入口の看板・X に載る絵）
   ============================================================ */
import { 状態, 逃 } from "./共通.js";

/* 場所の絵と X に載る絵で同じにする決まり（2026-10-07 の2回目のリファクタリングで、2か所に書いていたものをここへ） */
// 座っている人を奥（y が小さい）から並べる。手前の人が上に重なるように
export const 奥から = (部屋, 席ら) => [...席ら].sort((a, b)=>(部屋.席[a.番]?.y || 0) - (部屋.席[b.番]?.y || 0));
/* 同じベンチに2人いるときは、2人目のユーザ名と書籍名を1段下げる
   （横に振り分けると、隣のブロックのユーザ名と書籍名とぶつかった） */
export const 下げるか = (席, 座られた番) => !!席.隣 && 座られた番.has(席.相方);

export const 置き = (席, 幅) => `left:${席.x}%;top:${席.y}%${幅 ? `;width:${席.幅}%` : ""}`;

/* 席ごとに、何をどちら向きに描くか（場所の絵・小さな絵・入口の看板・X に載る絵で共通。2026-10-10 に1か所へ）。
   座っている席：{ 席, 座る, めくる（アバターの絵の道）, 反転 }／空いている席：{ 席, 空き（空のベンチの絵）, 反転 }。
   ⚠️ 空のベンチも人も**まとめて**奥（y が小さい）から並べる（2026-10-04、芦ノ湖でベンチを前後2列にしたとき。
      前は空のベンチを先に全部描いていて、手前の空のベンチが、奥に座った人の下に隠れた）
   ⚠️ 手前の席（姿：背中）は背中を見せる。背中の絵が無い人は顔の絵のまま座る。
      いまの場所に手前の席は無く、背中の絵も作っていない（2026-10-10 配信者。functions の注） */
export function 描くもの(部屋, 席ら){
  const 座られた = new Map(席ら.map(s=>[s.番, s]));
  return 部屋.席.flatMap((席, 番)=>{
    const s = 座られた.get(番);
    if(s){
      const 人 = 状態.人々.get(s.uid), a = 人?.アバター || {};
      const 背中 = 席.姿 === "背中" && !!a.背中;
      return [{ 席, 座る:背中 ? a.背中 : a.座る, めくる:背中 ? a.背中 : a.めくる, 反転:反転するか(人, 席, 背中) }];
    }
    // だれも座っていない席には、空のベンチを置く（場所に 空き の絵があるときだけ）。絵の向きは 空きの向き
    return 部屋.空き ? [{ 席, 空き:部屋.空き[席.姿] || 部屋.空き.顔, 反転:空きを反転するか(部屋, 席) }] : [];
  }).sort((a, b)=>a.席.y - b.席.y);
}

// 場所の絵の上に置く、空のベンチと座っている人（ユーザ名と書籍名は 場所.js が別の層に重ねる）
export function 人とベンチ(部屋, 席ら){
  return 描くもの(部屋, 席ら).map(x=>`
    <div class="人 ${x.空き ? "空き" : ""} ${x.反転 ? "左向き" : ""}" style="${置き(x.席, true)}">
      <div class="姿">${x.空き ? `<img class="座る" src="${x.空き}" alt="">`
        : `<img class="座る" data-道="${逃(x.座る)}" alt=""><img class="めくる" data-道="${逃(x.めくる)}" alt="">`}</div>
    </div>`).join("");
}

/* 席の向きと、絵の向きが違えば左右を反転する。
   ⚠️ 絵は「右前を向く」と頼んでも左を向くことがあるので、描いたあとに見た向き（アバター.向き）を使う。
      本人が「向きを反対にする」を押していたら、さらに逆にする */
// 空のベンチの絵の向き（部屋.空きの向き。書いていなければ右）と、席の向きが違えば反転する
export function 空きを反転するか(部屋, 席){
  const 絵の向き = 部屋.空きの向き?.[席.姿] || "右";
  return 絵の向き !== 席.向き;
}

export function 反転するか(人, 席, 背中){
  const a = 人?.アバター || {};
  if(背中) return (a.背中の向き === "left" ? "左" : "右") !== 席.向き;
  let 絵の向き = a.向き === "left" ? "左" : "右";
  if(人?.反転) 絵の向き = 絵の向き === "左" ? "右" : "左";
  return 絵の向き !== 席.向き;
}
