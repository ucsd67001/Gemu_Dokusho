import { 部屋ら } from "../部屋.js";
import { 土台, 根, 状態, 動き, 自分の席, 逃, 知らせる, 窓を出す, 窓を閉じる, 行く, 時間に, 待ちの画面 } from "./共通.js";
import { 戻りの窓 } from "./場所.js";
import { 前の本を忘れる } from "./本を選ぶ.js";
import { 共有の絵を描く } from "./Xに載る絵.js";

/* ── 読み終える ─────────────────────────────
   2026-09-27 配信者：X への投稿は、読み終えるときに「投稿しますか？」と聞き、
   はいなら、絵・書名・読んだ時間と一緒に投稿する。
   ⚠️ X の投稿画面を開く形（intent）では、画像を添付できない。
      → 絵を置いた「読書の記録ページ」（/s/{id}。functions の sharePage）のリンクを付ける。
        X がリンクから絵（og:image）を読み取り、投稿に大きく出す。**配信者はこの形でよい**（2026-09-27、実際の投稿を見て）
      ⚠️ 一度「画像を添付したい」と受け取り、パソコンはコピーして貼り付け、スマホは画像を保存…の手順を作ったが、
         取り違えだった。**保存や貼り付けの手順は要らない**（配信者）。
      ⚠️ スマホは、準備ができたら「X のアプリで投稿する」「共有から投稿する」「ブラウザの X で投稿する」から選んでもらう
         （下の 投稿して終える の注。新しい窓は止められて X が立ち上がらず、x.com のリンクではアプリの中のブラウザが開いた）
   ⚠️ 絵には座っている全員が写り、全員に名札（名前と題）を付ける（2026-09-30 配信者が許した） */
let 読み終えの絵 = null, 読み終えの中身 = null;

function 読み終える窓(){
  const 席 = 土台.座っている();
  if(!席) return 終える();
  if(土台.離れていた時間() >= 土台.聞く離れ) return 戻りの窓(土台.離れていた時間());
  const 題 = 自分の席()?.題 ?? "";
  const 本 = 席.区切り?.at(-1)?.本 || "";
  const 分 = Math.max(1, Math.round(土台.読んだ時間() / 60000));
  const 場所 = 部屋ら[状態.部屋].名;
  読み終えの絵 = null;
  読み終えの中身 = { 題, 本, 分, 場所 };
  窓を出す("読み終える", `
    <p class="窓の文">${題 ? `『${逃(題)}』を、` : ""}${逃(場所)}のベンチで <b>${時間に(分)}</b> 読みました。</p>
    ${題 ? `<label class="読了の印"><input type="checkbox" id="読了の印"> この本を最後まで読んだ（読了）</label>` : ""}
    <div id="総ページの欄" hidden>
      <label class="名札" for="総ページ">この本の総ページ数（わかれば）</label>
      <input id="総ページ" class="欄" type="number" inputmode="numeric" min="0" max="20000" placeholder="例：320"
        value="${状態.いまの本?.id === 本 && 状態.いまの本.ページ ? 状態.いまの本.ページ : ""}">
    </div>
    <div class="共有の見本" id="共有の見本">${待ちの画面("絵を描いています")}</div>
    <p class="窓の文">X に投稿しますか？</p>
    <div class="窓の釦">
      <button class="釦 全幅" data-する="投稿して終える" disabled>X に投稿して終える</button>
      <button class="釦 枠だけ 全幅" data-する="そのまま終える">投稿しないで終える</button>
    </div>
    <p class="注">投稿には、この絵と、書籍名と、読んだ時間が入ります。絵には、その場にいる人のユーザ名と書籍名も写ります。</p>`);
  共有の絵を描く(題, 分, 場所).then(絵=>{
    読み終えの絵 = 絵;
    const 見本 = document.getElementById("共有の見本");
    if(見本) 見本.innerHTML = `<img src="${URL.createObjectURL(絵)}" alt="投稿する絵">`;
  }).catch(e=>{
    console.error(e);
    const 見本 = document.getElementById("共有の見本");
    if(見本) 見本.innerHTML = `<p class="注">絵を描けませんでした。文だけで投稿できます。</p>`;
  }).finally(()=>{
    const 釦 = document.querySelector("[data-する=投稿して終える]");
    if(釦) 釦.disabled = false;
  });
}

// 「読み終える」で終えたときだけ、読んだ時間を記録に残す（2026-09-29 配信者）
// 読了の印と総ページ数（窓が閉じる前に読む）。冊数とページ数は、ここで印を付けた本だけを数える（2026-09-29 配信者）
function 読了を読む(){
  if(!document.getElementById("読了の印")?.checked || !読み終えの中身) return null;
  const ページ = Math.max(0, Math.min(20000, Math.round(Number(document.getElementById("総ページ")?.value) || 0)));
  return { 題:読み終えの中身.題, ページ, 本:読み終えの中身.本 };
}

// スマホで投稿の準備をしたあと（記録はもう残してある）
let 投稿の文 = "";

function 投稿のあとを片づける(){
  窓を閉じる();
  行く("廊下");
  知らせる("おつかれさまでした");
}

async function 終える(){
  const 読了 = 読了を読む();
  if(読了) 前の本を忘れる();
  窓を閉じる();
  await 土台.立つ({ 記録する:true, 読了 }).catch(()=>{});
  行く("廊下");
  知らせる("おつかれさまでした");
}

// 読了の印を付けたら、総ページ数の欄を出す
document.addEventListener("change", e=>{
  if(e.target.id !== "読了の印") return;
  const 欄 = document.getElementById("総ページの欄");
  if(欄){ 欄.hidden = !e.target.checked; if(e.target.checked) document.getElementById("総ページ")?.focus(); }
});

Object.assign(動き, {
  読み終える: ()=>読み終える窓(),
  // ⚠️ 2026-09-27 に行の範囲で消したとき、これまで消えていた（「投稿しないで終える」が効かなかった）
  そのまま終える: ()=>終える(),
  /* スマホで「X で投稿する」を押した：リンクはそのまま開かせる（止めない）。
     アプリが開いたときは、このページが残るので、戻ってきたら場所の一覧へ。
     ブラウザで X が開いたときは、このページごと移るので、何もしなくてよい */
  Xへ移る: el=>{
    let 済み = false;
    const 片づける = ()=>{
      if(済み) return;
      済み = true;
      removeEventListener("visibilitychange", 戻った);
      投稿のあとを片づける();
    };
    const 戻った = ()=>{ if(!document.hidden) 片づける(); };
    addEventListener("visibilitychange", 戻った);
    // アプリの呼び出しは、アプリが無いと何も起きない（このページのまま）。ほかの方法を選べるように、戻ってくるまで窓を閉じない
    if(!el.dataset.戻るまで) setTimeout(()=>{ if(!document.hidden) 片づける(); }, 3000);
  },
  // 共有シート（X の投稿画面が、アプリの中で開く）。やめたときは窓を残す
  共有から投稿する: ()=>{
    navigator.share({ text:投稿の文 })
      .then(()=>投稿のあとを片づける())
      .catch(e=>{ if(e?.name !== "AbortError") 知らせる("共有を開けませんでした", true); });
  },
  投稿しないで閉じる: ()=>投稿のあとを片づける(),
  投稿して終える: async el=>{
    el.disabled = true;
    el.textContent = "投稿の準備をしています…";
    const { 題, 分, 場所 } = 読み終えの中身;
    const 文 = 題 ? `『${題}』を${時間に(分)}、${場所}のベンチで読みました。` : `${場所}のベンチで、${時間に(分)}読みました。`;
    const スマホ = matchMedia("(pointer: coarse)").matches;
    // パソコン：窓は押した瞬間に開く（絵を置き終わってから開くと、ポップアップとして止められる）
    const 窓 = スマホ ? null : open("", "_blank");
    let 行き先 = location.origin + 根;
    try{ if(読み終えの絵) 行き先 = await 土台.共有を作る(読み終えの絵, { 題, 分, 場所 }); }
    catch(e){ console.error(e); }
    /* 文・ハッシュタグ・リンクのあいだに空の行を1つずつ（2026-09-29 配信者）。
       ⚠️ リンクは url= で渡さず、文に入れる。url= だと X が文のすぐ後ろ（同じ行）につなげる */
    const 先 = "https://x.com/intent/post?text=" + encodeURIComponent(`${文}\n\n#GEMuの静かな読書会\n\n${行き先}`);
    const 読了 = 読了を読む();
    if(読了) 前の本を忘れる();
    await 土台.立つ({ 記録する:true, 読了 }).catch(()=>{});
    /* ⚠️⚠️ スマホ：準備ができたら「X で投稿する」を**本人に押してもらう**（2026-10-04 配信者が①を選んだ）。
       スマホは、人が自分でリンクを押したときだけ「X のアプリが入っていればアプリで開く」。
       前は絵を置き終わってから、ページの側で X へ移っていた（location.href）ので、押したことにならず、ウェブ版の X が開いていた。
       ⚠️ 絵を置き終わってから新しい窓を開くと、スマホでは止められて、X が立ち上がらなかった（2026-09-27 配信者）。リンクは同じタブで開く */
    /* ⚠️⚠️ 2026-10-04 配信者の iPhone：x.com の投稿画面のリンクを押すと X のアプリは起動したが、
       **アプリは投稿画面を開かず、アプリの中のブラウザで x.com を開いた**（ログインが別扱いで、ログイン画面が出た。
       そこでは Google のログインも止められている）。
       → ①アプリ専用の呼び出し（twitter://post）で、アプリの投稿画面を直接開く ②共有シートから X を選ぶ
         ③ブラウザの X（いままでの形。アプリが無い人用）の3つを出す */
    if(スマホ){
      投稿の文 = `${文}\n\n#GEMuの静かな読書会\n\n${行き先}`;
      const アプリへ = "twitter://post?message=" + encodeURIComponent(投稿の文);
      窓を出す("X に投稿する", `
        <p class="窓の文">準備ができました。読んだ時間は記録に残しました。</p>
        <div class="窓の釦">
          <a class="釦 全幅" href="${逃(アプリへ)}" data-する="Xへ移る" data-戻るまで="1">X のアプリで投稿する</a>
          ${navigator.share ? `<button class="釦 枠だけ 全幅" data-する="共有から投稿する">共有から投稿する（X を選ぶ）</button>` : ""}
          <button class="釦 枠だけ 全幅" data-する="投稿しないで閉じる">投稿しないで閉じる</button>
        </div>
        <p class="注">アプリで開かないときは、「共有から投稿する」で X を選んでください。X のアプリが無いときは、
          <a href="${逃(先)}" data-する="Xへ移る">ブラウザの X で投稿する</a>。</p>`, { 閉じられない:true });
      return;
    }
    if(窓){ 窓.opener = null; 窓.location.href = 先; }
    else open(先, "_blank", "noopener");
    await 終える();
  },
});
