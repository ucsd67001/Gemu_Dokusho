/* 二人掛けを、席2つに開く。b はベンチの**左端の人**の足もと。
   2人目の席は、ベンチの長い辺にそって、幅の半分だけ右へずらす。
   縦は 0.19×（幅の半分）×1.5（絵の縦横比 3:2 なので、縦の % は横の 1.5 倍）≒ 幅×0.14。
   南東向きは上へ、南西向きは下へ */
function 二人掛け(ベンチら){
  // 相方 … 同じベンチのもう一つの席の番号（2人そろったら、2人目のユーザ名と書籍名を1段下げるため）
  const 片側 = ベンチら.map((b, i) => ({ ...b, 相方: ベンチら.length + i }));
  const 隣 = ベンチら.map((b, i) => ({ ...b, 隣: true, 相方: i,
    x: b.x + b.幅 * 0.5,
    y: b.y + (b.向き === "左" ? 1 : -1) * b.幅 * 0.14 }));
  return [...片側, ...隣];
}

