/* 二人掛けを、席2つに開く。b はベンチの左奥の端の人の足もと。
   2人目の席は、ベンチの長い辺にそって、幅の半分だけ横へ、少し手前へずらす
   （絵の縦横比 3:2 なので、縦の % は横の 1.5 倍に直す） */
function 二人掛け(ベンチら){
  // 相方 … 同じベンチのもう一つの席の番号（名札を左右に振り分けるため）
  const 片側 = ベンチら.map((b, i) => ({ ...b, 相方: ベンチら.length + i }));
  const 隣 = ベンチら.map((b, i) => ({ ...b, 隣: true, 相方: i,
    x: b.x + (b.向き === "左" ? -1 : 1) * b.幅 * 0.5,
    y: b.y + b.幅 * 0.14 * 1.5 }));
  return [...片側, ...隣];
}

