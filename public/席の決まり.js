/* 席を保つ時間。⚠️ firestore.rules の stale() と同じ12時間にそろえる（CLAUDE.md の「知らずに触ると壊す」4）。
   前は3分。画面を消して読む人のために 12時間にした（2026-10-04 配信者） */
export const 古いとみなす = 12 * 60 * 60 * 1000;

/* ⚠️⚠️ 画面を消して読むとき（2026-10-04 配信者）。
   使い方は「場所に入る → スマホの画面を消して本を読む → 読み終えたら画面をつけて、読み終える」。
   **3時間以上** 離れてから戻ったら（配信者「30分以上 ⇒ 3時間以上」）、画面が「そのあいだに読んだ時間」を聞き、
   読んでいなかった時間は **休み** として、記録から引く。3時間より短ければ、そのまま読んでいたものとする。
   12時間を過ぎたら席が空き、その回は記録に残らない */
export const 聞く離れ = 3 * 60 * 60 * 1000;

// ⚠️ 記録に保存する印（画面には出さない。記録のページは「（書籍名を出さずに読んだ回）」と出す）。functions の集計もこの文字で見分ける
export const 題を出さない印 = "（題を出さずに読んだ本）";

/* 座っているあいだの覚え（いま）の形：
     { 部屋, 番, 入った, 休み:[{ から, まで }], 最後に生きていた, 区切り:[{ 題, 本, 始め }] }
   題が空＝書籍名を出さない。区切りは本を替えるたびに足す */
export const 座った覚え = (部屋, 番, 入った, 題, 本, 最後に生きていた = 入った) =>
  ({ 部屋, 番, 入った, 休み:[], 最後に生きていた, 区切り:[{ 題, 本:本 || "", 始め:入った }] });

// [a, b] から休みを引いた区間たち（1秒に満たない区間は捨てる）
function 休みを引く(a, b, 休み = []){
  let 区間 = [[a, b]];
  for(const h of 休み){
    区間 = 区間.flatMap(([x, y])=>{
      if(h.まで <= x || h.から >= y) return [[x, y]];
      const 残り = [];
      if(h.から > x) 残り.push([x, h.から]);
      if(h.まで < y) 残り.push([h.まで, y]);
      return 残り;
    });
  }
  return 区間.filter(([x, y])=>y - x >= 1000);
}

// 休みを引いた、読んだ時間（ミリ秒）
export const 読んだ時間を数える = (いま, 今 = Date.now()) =>
  いま ? 休みを引く(いま.入った, 今, いま.休み).reduce((s, [x, y])=>s + y - x, 0) : 0;

export const 離れていた時間を数える = (いま, 今 = Date.now()) =>
  いま ? 今 - (いま.最後に生きていた || 今) : 0;

// 離れていたあいだに読んだ分（自己申告）を いま に書き込む。それより後ろの、戻るまでの時間は休みにする
export function 離席を書き込む(いま, 読んだ分, 今 = Date.now()){
  if(!いま) return;
  const から = いま.最後に生きていた || 今;
  const 読み終わり = Math.min(今, から + Math.max(0, 読んだ分) * 60000);
  if(読み終わり < 今) (いま.休み ||= []).push({ から:読み終わり, まで:今 });
  いま.最後に生きていた = 今;
}

/* 記録に書く1件ずつ：区切りごとに、休みを引いて分かれた区間ごと。
   ⚠️ 書籍名を出さなかった区切りも、時間は残す（自分の記録にだけ「書籍名を出さずに読んだ回」として） */
export function 記録にする(いま, 終わり = Date.now()){
  return いま.区切り.flatMap((k, i)=>{
    const 次 = いま.区切り[i + 1]?.始め ?? 終わり;
    return 休みを引く(k.始め, 次, いま.休み).map(([始め, 終]) =>
      ({ 部屋:いま.部屋, 題:k.題 || 題を出さない印, 本:k.本 || "", 始め, 終わり:終 }));
  });
}

/* ⚠️⚠️ 同じ人が PC とスマホの両方で開いたとき（2026-09-30 配信者「本を替えるが効かない」「PC とスマホで整合が取れない」）。
   前は、あとから座った端末が前の端末の席を消すのに、**前の端末は座っているつもりのまま**だった
   （「本を替える」は消えた席を書き換えようとして失敗し、「生きている」も空振りしていた）。
   → 席の様子が届くたびに、この端末の いま と、データベースの自分の席を突き合わせる：
     ・ほかの端末で座っている → この端末も、その席に座っている扱いにする（どちらからでも替えられ、読み終えられる）
     ・ほかの端末で本を替えた → この端末の区切りにも足す（記録が本ごとに正しく分かれる）
     ・ほかの端末で席を立った → この端末も立った扱いにする（"ほかで立った"）。12時間を過ぎていたら "長く離れて立った"
   返すもの：{ いま（新しい覚え。変わらなければ同じもの）, 出来事 } */
export function 席を突き合わせる(いま, 部屋, 自分の席, 今 = Date.now()){
  if(いま && いま.部屋 === 部屋){
    if(!自分の席 || 自分の席.番 !== いま.番){
      const 長く離れた = 今 - (いま.最後に生きていた || 0) > 古いとみなす;
      return { いま:null, 出来事:長く離れた ? "長く離れて立った" : "ほかで立った" };
    }
    const 前 = いま.区切り.at(-1);
    if(自分の席.題 !== 前.題 || (自分の席.本 || "") !== (前.本 || ""))
      いま.区切り.push({ 題:自分の席.題, 本:自分の席.本 || "", 始め:今 });
    return { いま, 出来事:null };
  }
  if(!いま && 自分の席){
    // 最後に生きていた＝席の seen（画面を消して戻ったら、ここからの時間を聞く）
    return { いま:座った覚え(部屋, 自分の席.番, 自分の席.入った, 自分の席.題, 自分の席.本, 自分の席.見た),
      出来事:"ほかで座っていた" };
  }
  return { いま, 出来事:null };
}

